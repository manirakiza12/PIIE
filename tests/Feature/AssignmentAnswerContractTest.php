/**
 * THE ANSWER CONTRACT: accepted response types are ALTERNATIVES, not a checklist.
 *
 * THE FAILING CASE, REPRODUCED EXACTLY
 *
 * A lecturer ticks "Written response" and "Document" on a question. The student's
 * browser renders a textarea for the first and a file picker for the second, and
 * the picker is accompanied by a HIDDEN `kind` input so the server knows which
 * allowlist to check the file against.
 *
 * The student types an answer and chooses no file. The browser still submits:
 *
 *     questions[1][text]            = "Gross profit is 4,200."
 *     questions[1][items][0][kind]  = "document"      <- the hidden input
 *     questions[1][items][0][file]  = (nothing)
 *
 * A hidden input is present whether or not the student used the slot. So a slot
 * the student DID NOT USE arrives looking exactly like a slot they declared and
 * failed to complete - and a validator that insists on a file for every declared
 * kind turns an answered question into "Choose a file for question 1."
 *
 * That is the AND-instead-of-OR the manual test hit. It is a bug about EMPTY
 * SLOTS, and it is worth naming precisely because "the validator treated the
 * types as AND" describes the SYMPTOM while missing the mechanism - and the
 * mechanism is what has to be fixed, or the next empty slot re-breaks it.
 *
 * THE CONTRACT, STATED ONCE
 *
 *   A question's accepted response types are ALTERNATIVE ways of answering it.
 *
 *     [written, document]   any ONE of them, or several, satisfies the question
 *     [audio]               an upload OR a browser recording satisfies it
 *     [video]               ditto
 *     [link]                a valid URL satisfies it; no file is wanted
 *
 *   A REQUIRED question is answered when AT LEAST ONE accepted type carries valid
 *   evidence. A required question is NEVER a requirement to supply every type.
 *
 *   An OPTIONAL question may be left alone entirely.
 *
 *   A slot that carries NO evidence is not an item at all. Declaring a slot is a
 *   statement about which allowlist applies; supplying evidence is the fact.
 *
 * This suite pins all of it, and every payload below is the SHAPE A BROWSER
 * SENDS - hidden `kind` fields included - rather than a hand-built array that
 * quietly omits the parts that caused the failure in the first place.
 */
