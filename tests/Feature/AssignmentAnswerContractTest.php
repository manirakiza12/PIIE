    public function test_an_unconfirmed_student_cannot_submit(): void
    {
        $k = self::K;

        $assignment = $this->publishedAssignment([
            'max_marks' => 5, 'instructions' => '<p>Do the work.</p>', 'due_date' => now()->addWeek(),
        ]);
        $question = $this->questionAcceptingAnyOf($assignment, [$k::KIND_TEXT, $k::KIND_DOCUMENT]);

        \Illuminate\Support\Facades\DB::table('course_registrations')
            ->where('student_id', $this->student->id)
            ->update(['status' => 'registered']);

        $this->submitPaper($assignment, [
            (string) $question->id => $this->browserAnswer($question, ['text' => '<p>Mine.</p>']),
        ])->assertNotFound();

        $this->assertSame(0, AssignmentSubmission::query()->count());
    }

