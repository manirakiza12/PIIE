    private function realPaper(): array
    {
        $k = self::K;

        $assignment = $this->publishedAssignment([
            'title' => 'Module 1 Assessment',
            'max_marks' => 20,
            'due_date' => now()->addWeek(),
            'allowed_attempts' => 2,
        ]);

        $this->questionAcceptingAnyOf($assignment, [$k::KIND_TEXT, $k::KIND_DOCUMENT], [
            'heading' => 'Gross profit', 'prompt' => '<p>Calculate the gross profit.</p>', 'marks' => 5,
        ]);
        $this->questionAcceptingAnyOf($assignment, [$k::KIND_TEXT, $k::KIND_IMAGE], [
            'heading' => 'Working', 'prompt' => '<p>Upload a photograph of your working.</p>', 'marks' => 5,
        ]);
        $this->questionAccepting($assignment, $k::KIND_AUDIO, [
            'heading' => 'Explain orally', 'prompt' => '<p>Explain your reasoning orally.</p>', 'marks' => 5,
        ]);
        $this->questionAccepting($assignment, $k::KIND_VIDEO, [
            'heading' => 'Demonstrate', 'prompt' => '<p>Demonstrate the solution.</p>', 'marks' => 5,
        ]);

        return [$assignment, $this->questions($assignment)];
    }

