    public function test_the_error_names_the_question_and_what_it_accepts(): void
    {
        $k = self::K;

        $assignment = $this->publishedAssignment([
            'max_marks' => 20, 'instructions' => '<p>Do the work.</p>', 'due_date' => now()->addWeek(),
        ]);

        $q1 = $this->questionAcceptingAnyOf($assignment, [$k::KIND_TEXT, $k::KIND_DOCUMENT], ['marks' => 5]);
        $q2 = $this->questionAcceptingAnyOf($assignment, [$k::KIND_TEXT, $k::KIND_IMAGE], ['marks' => 5]);
        $q3 = $this->questionAccepting($assignment, $k::KIND_AUDIO, ['marks' => 5]);
        $q4 = $this->questionAccepting($assignment, $k::KIND_VIDEO, ['marks' => 5]);

        $response = $this->submitPaper($assignment, [
            (string) $q1->id => $this->browserAnswer($q1),
            (string) $q2->id => $this->browserAnswer($q2),
            (string) $q3->id => $this->browserAnswer($q3),
            (string) $q4->id => $this->browserAnswer($q4),
        ])->assertSessionHasErrors('questions');

        $messages = implode(' | ', (array) $response->getSession()->get('errors')->get('questions'));

        // ONE SENTENCE PER QUESTION, naming the alternatives that would answer it.
        //
        // The expected text is the whole sentence the model produces, with the
        // kinds joined by "or". Asserting the sentence rather than just the nouns
        // is deliberate: a message naming EVERY kind would satisfy a test that only
        // looked for the words, while promising exactly the behaviour that was
        // reported as broken.
        foreach ([
            ['question 1', 'Provide a written response or a document for question 1.'],
            ['question 2', 'Provide a written response or an image for question 2.'],
            ['question 3', 'Provide an audio response for question 3.'],
            ['question 4', 'Provide a video response for question 4.'],
        ] as [$label, $expected]) {
            $this->assertStringContainsString($expected, $messages, "the message for {$label}");
        }

        // THE WORD "or" IS THE CONTRACT, so it is asserted directly. A message
        // naming every kind is not enough: "provide a written response, an image,
        // a document AND an audio response" would satisfy a test that only checked
        // the nouns appear, while promising exactly the behaviour that was
        // reported as broken.
        $this->assertStringContainsString('or', $messages);
        $this->assertStringNotContainsString(' and ', $messages, 'the kinds are alternatives, not a checklist');

        // And never the misleading "choose a file" wording for a question the
        // student did not try to attach a file to.
        $this->assertStringNotContainsString('Choose a file', $messages);
    }

