    /**
     * The slot indexes the RENDERED FORM uses for one question, so a test cannot
     * accidentally post a tidier payload than the browser ever would.
     *
     * The textarea is not a slot. A file kind occupies one; a link occupies one.
     * A question accepting [text, document, image] therefore posts slots 0 and 1,
     * and slot 1 is the one that has to survive carrying nothing.
     *
     * @return array<int, array<string, mixed>>
     */
    private function browserSlots(\App\Models\AssignmentQuestion $question, ?string $text = null): array
    {
        $slots = [];
        $index = 0;

        if ($question->acceptsLink()) {
            // A link slot always posts its `kind` and its empty `url` input.
            $slots[$index] = ['kind' => self::K::KIND_LINK, 'url' => ''];
            $index++;
        }

        foreach ($question->acceptedFileKinds() as $kind) {
            // A file slot always posts its `kind`; the `file` key is absent unless
            // the student actually chose something. That asymmetry is the whole bug.
            $slots[$index] = ['kind' => $kind];
            $index++;
        }

        return array_filter($slots, static fn ($slot) => $slot !== []);
    }

    /**
     * One question's payload exactly as the form would send it.
     *
     * @return array<string, mixed>
     */
    private function browserAnswer(\App\Models\AssignmentQuestion $question, array $evidence = []): array
    {
        $payload = ['text' => null, 'items' => $this->browserSlots($question)];

        if ($question->acceptsWrittenResponse()) {
            $payload['text'] = $evidence['text'] ?? null;
        }

        // Merge in whatever the student actually supplied, by kind.
        foreach ($evidence as $key => $value) {
            if ($key === 'text') {
                continue;
            }
            foreach ($payload['items'] as $index => $slot) {
                if ($slot['kind'] === $key) {
                    $payload['items'][$index] = array_merge($slot, $value);
                }
            }
        }

        return $payload;
    }

